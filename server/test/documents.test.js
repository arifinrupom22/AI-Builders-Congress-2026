/**
 * The Office and rich-text readers.
 *
 * Every fixture here is generated from the same spec-shaped writers the sample
 * seeder uses, so the tests exercise real containers (ZIP central directories,
 * OLE2 FAT chains, Word piece tables, RTF control words) rather than a mock
 * that would agree with any implementation.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { extractText, SUPPORTED_EXTENSIONS } from '../src/documents/extract.js';
import { chunkPages } from '../src/documents/chunk.js';
import { makeDocx, makeLegacyDoc, makeZip } from '../../scripts/lib/minimal-office.mjs';

const BANGLA_NOTES = [
  'অধ্যায় ১: ডেটাবেস ট্রানজেকশন',
  'ট্রানজেকশন হল একগুচ্ছ অপারেশন যা একটি একক যৌক্তিক একক হিসেবে কাজ করে।',
  'ACID মানে Atomicity, Consistency, Isolation এবং Durability।',
  'Isolation নিশ্চিত করে যে সমান্তরাল ট্রানজেকশন একটি আরেকটিকে প্রভাবিত না করে।',
].join('\n');

const ENGLISH_PARAGRAPHS = [
  'A transaction is a unit of work that either completes entirely or not at all.',
  'Isolation levels trade consistency for concurrency, which is the usual engineering compromise.',
];

test('DOCX: paragraphs, headings and tables become readable study text', async () => {
  const buffer = makeDocx([
    { text: 'Database transactions', style: 'Heading1' },
    ...ENGLISH_PARAGRAPHS,
    { text: 'Isolation | Serialisable | Repeatable read' },
  ]);

  const result = await extractText({ buffer, filename: 'notes.docx', mimeType: '' });

  assert.equal(result.kind, 'docx');
  assert.equal(result.language, 'en');
  assert.equal(result.pageCount, 1);
  assert.match(result.pages[0].text, /^# Database transactions$/m, 'the heading style becomes a markdown heading');
  assert.match(result.pages[0].text, /completes entirely or not at all/);
  assert.ok(!result.pages[0].text.includes('<w:'), 'no raw XML may reach the index');
  assert.equal(result.warnings[0].code, 'docx_no_layout');
});

test('DOCX: Word page breaks become real page numbers for citations', async () => {
  const document = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>First page text about entropy.</w:t><w:br w:type="page"/></w:r></w:p><w:p><w:r><w:t>Second page text about free energy.</w:t></w:r></w:p></w:body></w:document>`;
  const buffer = makeZip([{ name: 'word/document.xml', data: document }]);

  const result = await extractText({ buffer, filename: 'paged.docx' });
  assert.equal(result.pageCount, 2);
  assert.equal(result.pages[0].pageNumber, 1);
  assert.equal(result.pages[1].pageNumber, 2);
  assert.match(result.pages[0].text, /entropy/);
  assert.match(result.pages[1].text, /free energy/);

  // The chunker must carry those page numbers through to the citation.
  const passages = chunkPages(result.pages, { materialId: 'm', documentName: 'paged.docx' });
  assert.ok(passages.some((p) => p.pageNumber === 2 && /free energy/.test(p.text)));
});

test('DOCX: Bangla content survives extraction and is detected as Bangla', async () => {
  const buffer = makeDocx([{ text: 'ডেটাবেস নোট', style: 'Heading1' }, ...BANGLA_NOTES.split('\n')]);
  const result = await extractText({ buffer, filename: 'bangla-notes.docx' });

  assert.equal(result.language, 'bn');
  assert.match(result.pages[0].text, /ডেটাবেস নোট/);
  assert.match(result.pages[0].text, /Atomicity, Consistency, Isolation/);
  assert.ok(!result.pages[0].text.includes('\uFFFD'), 'no replacement characters in Bangla text');
});

test('DOC: a Word 97-2003 file is read through its piece table, in English and Bangla', async () => {
  const english = await extractText({ buffer: makeLegacyDoc(ENGLISH_PARAGRAPHS.join('\n')), filename: 'old.doc' });
  assert.equal(english.kind, 'doc');
  assert.equal(english.language, 'en');
  assert.equal(english.charCount, ENGLISH_PARAGRAPHS.join('\n').length, 'every character round-trips');
  assert.match(english.pages[0].text, /Isolation levels trade consistency/);

  const bangla = await extractText({ buffer: makeLegacyDoc(BANGLA_NOTES), filename: 'bangla.doc' });
  assert.equal(bangla.language, 'bn');
  assert.equal(bangla.charCount, BANGLA_NOTES.length, 'UTF-16 Bangla text round-trips exactly');
  assert.ok(!bangla.pages[0].text.includes('\uFFFD'));
});

test('RTF: control words, metadata groups and unicode escapes are handled', async () => {
  const rtf = [
    String.raw`{\rtf1\ansi\ansicpg1252\deff0 {\fonttbl{\f0 Arial;\f1 Times New Roman;}}`,
    String.raw`{\info{\title Generated by a test}\creator TestTool}`,
    String.raw`\pard\f0 Database transactions\par A transaction is atomic and isolated.\par`,
    String.raw`\f1 Escaped: \'93quoted\'94 text.\par}`,
  ].join('');

  const result = await extractText({ buffer: Buffer.from(rtf, 'latin1'), filename: 'a.rtf' });

  assert.equal(result.kind, 'rtf');
  assert.equal(result.pageCount, 1);
  assert.match(result.pages[0].text, /Database transactions/);
  assert.match(result.pages[0].text, /A transaction is atomic and isolated\./);
  assert.ok(!result.pages[0].text.includes('fonttbl'), 'font tables are not document text');
  assert.ok(!result.pages[0].text.includes('creator'), 'info groups are not document text');
  assert.match(result.pages[0].text, /\u201cquoted\u201d/, 'cp1252 smart quotes decode');
});

test('RTF: Bangla written as \\u escapes and as UTF-8 byte runs both decode', async () => {
  // \uNNNN? is the portable way RTF carries non-ASCII text.
  const unicodeEscapes = Buffer.from(
    String.raw`{\rtf1\ansi\ansicpg1252\pard \u2476?\u2494?\u2434?\u2482?\u2494?\par}`,
    'latin1',
  );
  const fromEscapes = await extractText({ buffer: unicodeEscapes, filename: 'u.rtf' });
  assert.equal(fromEscapes.language, 'bn');
  assert.match(fromEscapes.pages[0].text, /বাংলা/);

  // WordPad writes Bangla as consecutive \'hh bytes with ansicpg65001.
  const utf8Bytes = Buffer.from(
    String.raw`{\rtf1\ansi\ansicpg65001\pard \'e0\'a6\'ac\'e0\'a6\'be\'e0\'a6\'82\par}`,
    'latin1',
  );
  const fromBytes = await extractText({ buffer: utf8Bytes, filename: 'b.rtf' });
  assert.equal(fromBytes.language, 'bn');
  assert.match(fromBytes.pages[0].text, /বাং/);
  assert.ok(!fromBytes.pages[0].text.includes('\uFFFD'));
});

test('ODT: paragraphs, headings and table rows are extracted', async () => {
  const content = `<?xml version="1.0" encoding="UTF-8"?>
<office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0"><office:body><office:text>
<text:h text:outline-level="1">Database transactions</text:h>
<text:p>A transaction is atomic and isolated.</text:p>
<text:p><text:s text:c="2"/>Extra spaces collapse to one.</text:p>
<table:table><table:table-row><table:table-cell><text:p>Isolation</text:p></table:table-cell><table:table-cell><text:p>Serialisable</text:p></table:table-cell></table:table-row></table:table>
</office:text></office:body></office:document-content>`;
  const buffer = makeZip([
    { name: 'mimetype', data: 'application/vnd.oasis.opendocument.text' },
    { name: 'content.xml', data: content },
  ]);

  const result = await extractText({ buffer, filename: 'notes.odt' });
  assert.equal(result.kind, 'odt');
  assert.match(result.pages[0].text, /^# Database transactions$/m);
  assert.match(result.pages[0].text, /atomic and isolated/);
  assert.match(result.pages[0].text, /Extra spaces collapse/, 'repeated <text:s> counts are honoured');
  assert.match(result.pages[0].text, /Isolation \| Serialisable/, 'table rows read as one line');
  assert.ok(!result.pages[0].text.includes('<text:'), 'no raw ODF markup reaches the index');
});

test('format detection: an Office file whose content contradicts its name is refused', async () => {
  await assert.rejects(
    () => extractText({ buffer: Buffer.from('this is just a plain sentence'), filename: 'notes.docx' }),
    (err) => {
      assert.equal(err.code, 'unsupported_type');
      assert.match(err.message, /named "\.docx"/);
      assert.match(err.message, /Re-export/);
      return true;
    },
  );

  await assert.rejects(() => extractText({ buffer: Buffer.from('x'), filename: 'notes.odt' }), {
    code: 'unsupported_type',
  });
});

test('every advertised extension is one the extractor can read', async () => {
  assert.deepEqual(SUPPORTED_EXTENSIONS, [
    '.pdf',
    '.txt',
    '.md',
    '.markdown',
    '.docx',
    '.doc',
    '.docm',
    '.rtf',
    '.odt',
  ]);
  for (const ext of SUPPORTED_EXTENSIONS) {
    assert.ok(ext.startsWith('.'), `${ext} must include the dot`);
  }
});
